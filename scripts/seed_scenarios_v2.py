# ── Lab helpers ──────────────────────────────────────────────────────────────
def Ln(ru, kk, value, unit, normal, lo, hi):
    """Numeric lab with normal range."""
    assert_not_vital(ru)
    assert_not_vital(kk)
    return {"name_ru": ru, "name_kk": kk, "value": value, "unit": unit,
            "normal": normal, "normal_min": lo, "normal_max": hi}


def Ls(ru, kk, value, normal, abnormal=True, image=None):
    """Textual/qualitative lab. is_abnormal explicit."""
    assert_not_vital(ru)
    assert_not_vital(kk)
    d = {"name_ru": ru, "name_kk": kk, "value": value, "unit": "",
         "normal": normal, "is_abnormal": abnormal}
    if image:
        d["image_url"] = image
    return d


